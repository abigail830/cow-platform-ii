#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = resolve(fileURLToPath(import.meta.url), '..');
const backendRoot = resolve(scriptDir, '..');
const catalogRoot = join(backendRoot, 'agent-catalog');
const agentsDir = join(backendRoot, 'src', 'agents');

const GENERATED_HEADER = `/** AUTO-GENERATED by scripts/sync-catalog-agents.mjs — do not edit. */\n`;

function discoverAgentIds() {
  if (!existsSync(catalogRoot)) return [];
  return readdirSync(catalogRoot)
    .filter((name) => {
      const dir = join(catalogRoot, name);
      return statSync(dir).isDirectory() && existsSync(join(dir, 'agent.yaml'));
    })
    .sort();
}

function renderAgentModule(agentId) {
  return `${GENERATED_HEADER}import { buildCatalogAgentExports } from '../agent-catalog/build-agent-module.ts';

const agent = buildCatalogAgentExports(${JSON.stringify(agentId)});

export const route = agent.route;
export const description = agent.description;
export default agent.definition;
`;
}

function main() {
  const ids = discoverAgentIds();
  if (ids.length === 0) {
    throw new Error(`No agents found under ${catalogRoot}`);
  }

  const expected = new Set(ids.map((id) => `${id}.ts`));
  for (const file of readdirSync(agentsDir)) {
    if (!file.endsWith('.ts')) continue;
    const full = join(agentsDir, file);
    const text = readFileSync(full, 'utf-8');
    if (!text.startsWith(GENERATED_HEADER.trim())) continue;
    if (!expected.has(file)) {
      rmSync(full);
      console.log(`Removed stale generated agent: ${file}`);
    }
  }

  for (const id of ids) {
    const outPath = join(agentsDir, `${id}.ts`);
    const next = renderAgentModule(id);
    const prev = existsSync(outPath) ? readFileSync(outPath, 'utf-8') : '';
    if (prev !== next) {
      writeFileSync(outPath, next);
      console.log(`Synced agent module: ${id}.ts`);
    }
  }

  console.log(`Catalog sync complete (${ids.length} agent(s)).`);
}

main();
