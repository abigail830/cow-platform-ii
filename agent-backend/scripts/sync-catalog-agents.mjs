#!/usr/bin/env node
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = resolve(fileURLToPath(import.meta.url), '..');
const backendRoot = resolve(scriptDir, '..');
const catalogRoot = join(backendRoot, 'agent-catalog');
const agentsDir = join(backendRoot, 'src', 'agents');
const channelsDir = join(backendRoot, 'src', 'channels');

const GENERATED_HEADER = `/** AUTO-GENERATED by scripts/sync-catalog-agents.mjs — do not edit. */\n`;

function discoverAgentIds() {
  if (!existsSync(catalogRoot)) return [];
  return readdirSync(catalogRoot)
    .filter((name) => {
      const dir = join(catalogRoot, name);
      return statSync(dir).isDirectory() && existsSync(join(dir, 'agent.yaml'));
    })
    .sort();
}

function renderAgentModule(agentId) {
  return `${GENERATED_HEADER}import { buildCatalogAgentExports } from '../agent-catalog/build-agent-module.ts';

const agent = buildCatalogAgentExports(${JSON.stringify(agentId)});

export const route = agent.route;
export const attachments = agent.attachments;
export const description = agent.description;
export default agent.definition;
`;
}

function renderA2aChannelModule(agentId) {
  return `${GENERATED_HEADER}import { buildCatalogA2aChannel } from '../flue/a2a/create-channel.ts';

export const channel = buildCatalogA2aChannel(${JSON.stringify(agentId)}).channel;
`;
}

function discoverA2aAgentIds() {
  return discoverAgentIds().filter((id) => {
    const yamlPath = join(catalogRoot, id, 'agent.yaml');
    const text = readFileSync(yamlPath, 'utf-8');
    return /\na2a:\s*\n/.test(`\n${text}`) || text.trimStart().startsWith('a2a:');
  });
}

function main() {
  const ids = discoverAgentIds();
  if (ids.length === 0) {
    throw new Error(`No agents found under ${catalogRoot}`);
  }

  const expected = new Set(ids.map((id) => `${id}.ts`));
  for (const file of readdirSync(agentsDir)) {
    if (!file.endsWith('.ts')) continue;
    const full = join(agentsDir, file);
    const text = readFileSync(full, 'utf-8');
    if (!text.startsWith(GENERATED_HEADER.trim())) continue;
    if (!expected.has(file)) {
      rmSync(full);
      console.log(`Removed stale generated agent: ${file}`);
    }
  }

  for (const id of ids) {
    const outPath = join(agentsDir, `${id}.ts`);
    const next = renderAgentModule(id);
    const prev = existsSync(outPath) ? readFileSync(outPath, 'utf-8') : '';
    if (prev !== next) {
      writeFileSync(outPath, next);
      console.log(`Synced agent module: ${id}.ts`);
    }
  }

  const a2aIds = discoverA2aAgentIds();
  const expectedChannels = new Set(a2aIds.map((id) => `${id}-a2a.ts`));
  if (!existsSync(channelsDir)) mkdirSync(channelsDir, { recursive: true });
  if (existsSync(channelsDir)) {
    for (const file of readdirSync(channelsDir)) {
      if (!file.endsWith('.ts')) continue;
      const full = join(channelsDir, file);
      const text = readFileSync(full, 'utf-8');
      if (!text.startsWith(GENERATED_HEADER.trim())) continue;
      if (!expectedChannels.has(file)) {
        rmSync(full);
        console.log(`Removed stale generated channel: ${file}`);
      }
    }
  }

  for (const id of a2aIds) {
    const outPath = join(channelsDir, `${id}-a2a.ts`);
    const next = renderA2aChannelModule(id);
    const prev = existsSync(outPath) ? readFileSync(outPath, 'utf-8') : '';
    if (prev !== next) {
      writeFileSync(outPath, next);
      console.log(`Synced A2A channel module: ${id}-a2a.ts`);
    }
  }

  console.log(`Catalog sync complete (${ids.length} agent(s), ${a2aIds.length} A2A channel(s)).`);
}

main();
